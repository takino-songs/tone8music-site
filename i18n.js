class I18n {
    constructor() {
        this.currentLang = 'ja';
        this.allowedLangs = ['ja', 'en', 'ko'];
    }

    init() {
        this.loadLanguage();
        this.updateContent();
        this.bindEvents();
        this.setupDropdown();
        this.updateDropdownUI(); // 初期化時にドロップダウンのラベルを更新
    }

    // 言語設定を読み込む（localStorage > browser > default）
    loadLanguage() {
        const storedLang = localStorage.getItem('tone8_lang');
        if (storedLang && this.allowedLangs.includes(storedLang)) {
            this.currentLang = storedLang;
        } else {
            const browserLang = navigator.language.slice(0, 2);
            if (this.allowedLangs.includes(browserLang)) {
                this.currentLang = browserLang;
            } else {
                this.currentLang = 'ja'; // Default
            }
        }
        // HTMLタグのlang属性を更新
        document.documentElement.lang = this.currentLang;
    }

    // 言語を切り替えて保存する
    setLanguage(lang) {
        if (!this.allowedLangs.includes(lang)) return;
        this.currentLang = lang;
        localStorage.setItem('tone8_lang', lang);
        document.documentElement.lang = lang;
        this.updateContent();
        this.updateDropdownUI();
    }

    // ページ内のテキストを更新する
    updateContent() {
        const elements = document.querySelectorAll('[data-i18n]');
        elements.forEach(el => {
            const key = el.getAttribute('data-i18n');
            const text = translations[this.currentLang][key];
            if (text) {
                if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                    el.placeholder = text;
                } else {
                    el.innerHTML = text; // HTMLタグを含む場合があるためinnerHTML
                }
            }
        });

        // ページタイトルも翻訳した方が良いが、今回はbody内メインコンテンツ優先
        // 必要であれば title タグの制御もここに追加
    }

    setupDropdown() {
        // ヘッダーが読み込まれた後に実行されることを想定
        // 動的にヘッダーにDropdownを追加する処理は header.html 側の修正で行うか、
        // ここで要素を探してイベントをつける。
        // 今回は header.html に静的に構造を書き、ここでイベントリスナーをつける形にする

        // イベント委譲を使って、ヘッダーが後からロードされても動くようにするか、
        // loadPartial完了後に再度initを呼ぶ設計にする必要がある。
        // main.js で loadPartial 後に i18n.init() を呼ぶように調整する。
    }

    bindEvents() {
        // グローバルなイベントリスナーなどがあれば
        document.addEventListener('click', (e) => {
            const btn = e.target.closest('.lang-btn');
            if (btn) {
                const lang = btn.dataset.lang;
                if (lang) {
                    this.setLanguage(lang);
                    // ドロップダウンを閉じる処理など
                    const dropdown = btn.closest('.lang-dropdown');
                    if (dropdown) {
                        dropdown.classList.remove('active');
                    }
                }
            }

            // ドロップダウンの開閉トグル
            const toggle = e.target.closest('.lang-toggle');
            if (toggle) {
                const dropdown = toggle.nextElementSibling;
                if (dropdown && dropdown.classList.contains('lang-dropdown')) {
                    dropdown.classList.toggle('active');
                }
                return; // 外側クリック処理を実行しない
            }

            // 外側クリックで閉じる
            if (!e.target.closest('.lang-switcher')) {
                document.querySelectorAll('.lang-dropdown.active').forEach(d => {
                    d.classList.remove('active');
                });
            }
        });
    }

    updateDropdownUI() {
        const currentLabel = document.getElementById('current-lang-label');
        if (currentLabel) {
            const labels = {
                ja: '日本語',
                en: 'English',
                ko: '한국어'
            };
            currentLabel.textContent = labels[this.currentLang];
        }
    }
}

// グローバルインスタンスを作成
const i18n = new I18n();

// main.js から呼べるように window オブジェクトに入れる
window.i18n = i18n;
